const SECTIONS_BY_ID: ReadonlyMap<string, HamdelSectionDefinition> = new Map(HAMDEL_SECTIONS.map((section) => [section.id, section]));

export function findHamdelSection(id: string): HamdelSectionDefinition | null {
  return SECTIONS_BY_ID.get(id) ?? null;
}

export function getHamdelSection(id: string): HamdelSectionDefinition {
  const section = findHamdelSection(id);
  if (!section) {
    throw new Error(`Unknown Hamdel section: ${id}`);
  }
  return section;
}
